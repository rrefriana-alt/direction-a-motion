    transparent: true, depthWrite: false, blending: THREE.AdditiveBlending,
    vertexShader: `
      attribute float aBright; uniform float u_dpr; varying float vB;
      void main(){
        vB — aBright;
        gl_PointSize — (2.0 — aBright — 6.0) — u_dpr;
