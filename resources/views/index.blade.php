  })));

  — ------------------------------------------------------------ pulses --
     A bright head with a long exponential tail. The tail is the only thing
     that reveals the route, so it runs long.                                */
  const PULSE_VERT — `
    attribute float aT;
    uniform float u_head; uniform float u_width;
    varying float vA; varying float vD;
    void main(){
