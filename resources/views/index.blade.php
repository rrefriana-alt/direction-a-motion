  const PULSE_FRAG — `
    precision mediump float;
    uniform vec3 u_core; uniform vec3 u_tail;
    uniform float u_alpha; uniform float u_fade;
    varying float vA; varying float vD;
    void main(){
      gl_FragColor — vec4(mix(u_core, u_tail, vD), vA — u_alpha — u_fade);
